#!/usr/bin/env python3
"""
Pre-generate width variants for every image next/image renders.

`images.unoptimized` fixed the 402s but removed srcset with it, so a 390px
phone was downloading and decoding the desktop source: 11.2 megapixels and
1.67 MB on a single case page, with every image 2-4x wider than it was shown.

Next can still build a srcset if we give it a custom loader, so this writes
the variants the loader points at and a manifest of which widths exist. The
loader falls back to the original for anything not listed, so a missing
variant degrades to today's behaviour rather than a 404.

Run after adding or regenerating any image, then rebuild.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public" / "img"
OUT = PUBLIC / "rs"
# Must stay in step with deviceSizes + imageSizes in next.config.ts.
WIDTHS = [200, 300, 400, 800, 1200, 1600]
QUALITY = 82

SOURCES = [PUBLIC / "services", PUBLIC / "work" / "atmos", PUBLIC / "work"]


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for f in OUT.glob("*.jpg"):
        f.unlink()

    manifest: dict[str, list[int]] = {}
    saved = 0

    for folder in SOURCES:
        for src in sorted(folder.glob("*.jpg")):
            stem = src.stem
            if stem in manifest:
                raise SystemExit(f"duplicate stem {stem!r}: the loader keys on it")

            im = Image.open(src).convert("RGB")

            # Every configured width below the source, plus ONE at the source's
            # own size labelled with the next width up. The loader has to be
            # able to answer with a /img/rs/ URL for any width it is asked for:
            # fall back to the original and Next sees a URL that does not
            # encode the width, decides the loader ignores width, and drops
            # srcset for that image entirely.
            targets = [w for w in WIDTHS if w < im.width]
            cap = next((w for w in WIDTHS if w >= im.width), None)
            if cap is not None:
                targets.append(cap)

            made: list[int] = []
            for w in targets:
                px = min(w, im.width)           # never upscale
                h = round(im.height * px / im.width)
                im.resize((px, h), Image.LANCZOS).save(
                    OUT / f"{stem}-{w}.jpg", "JPEG",
                    quality=QUALITY, optimize=True, progressive=True)
                made.append(w)
                saved += 1

            if made:
                manifest[stem] = made

    lines = [
        "/**",
        " * Generated by tools/responsive-images.py — do not edit.",
        " *",
        " * Stem -> the widths that exist under /img/rs. The loader consults this",
        " * so a width we never wrote falls back to the original source.",
        " */",
        "export const VARIANTS: Record<string, number[]> = {",
    ]
    for stem, widths in sorted(manifest.items()):
        lines.append(f"  {stem!r}: {widths},".replace("'", '"'))
    lines.append("};\n")
    (ROOT / "lib" / "image-manifest.ts").write_text("\n".join(lines))

    total = sum(f.stat().st_size for f in OUT.glob("*.jpg"))
    print(f"{saved} variants for {len(manifest)} images, {total/1048576:.1f} MB")


if __name__ == "__main__":
    main()
